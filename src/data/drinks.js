export const getDrinkVibe = d => {
  if (VIBE_OVERRIDES[d.name]) return VIBE_OVERRIDES[d.name];
  const core = d.flavors.filter(isCoreFlavor);
  const fruitCount = core.filter(f => FRUITY.includes(f)).length;
  const sweetCount = core.filter(f => SWEET.includes(f)).length;
  const spiceCount = core.filter(f => SPICED.includes(f)).length;
  if (d.seasonal) return "seasonal";
  if (fruitCount >= 3) return "tropical";
  if (spiceCount > 0 && sweetCount > 0) return "cozy";
  if (spiceCount > 0) return "cozy";
  if (fruitCount > 0 && sweetCount > 0) return "fusion";
  if (fruitCount >= 2) return "fruity";
  if (sweetCount >= 2) return "indulgent";
  if (fruitCount === 1) return "fruity";
  if (sweetCount === 1) return "sweet";
  return "sweet";
};

export const getDrinkBaseCategory = d => {
  const hasChai = d.flavors.includes("Chai");
  const hasWhiteCoffee = d.flavors.includes("White Coffee");
  const vibe = getDrinkVibe(d);

  if (hasChai || hasWhiteCoffee || ["cozy", "indulgent", "sweet"].includes(vibe)) {
    return "coffee";
  } else if (["tropical", "fruity"].includes(vibe)) {
    return "rebel";
  } else if (vibe === "fusion") {
    const hasAnyFruit = d.flavors.some(f => f.includes("Any Fruit"));
    const fruitishCount = d.flavors.filter(f => FRUITY.includes(f) || f.includes("Float")).length;
    const sweetCount = d.flavors.filter(f => SWEET.includes(f)).length;
    if (hasAnyFruit || fruitishCount > sweetCount) {
      return "rebel";
    } else {
      return "coffee";
    }
  }
  return "coffee";
};

